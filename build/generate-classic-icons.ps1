#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Downloads the classic desktop icon set and generates the Avalonia resource dictionary for it.

.DESCRIPTION
    The interface is styled after Win32-era administration utilities, and Material Symbols — thin
    monochrome outlines on a 24x24 grid — read as a modern web application no matter how the rest
    of the chrome is drawn. This set is the Tango Icon Library 0.8.90 instead: the icon language
    of GNOME 2, Windows-era GTK ports and a generation of desktop utilities.

    Licence: the Tango Icon Library is released into the public domain, which imposes no
    attribution obligation on this repository or on anyone who clones it. The COPYING file of the
    upstream mirror is downloaded alongside the icons so the claim is auditable rather than
    asserted in a comment.

    Rasters, not geometry. Tango icons are multi-path artwork with gradients and highlights; they
    cannot be flattened into a single StreamGeometry the way a Material Symbol can, and rendering
    SVG would mean taking a new runtime dependency. The 64px PNGs are downloaded once, committed,
    and drawn at 16px and 20px with high-quality interpolation, so a 200% DPI display still has
    more source pixels than it needs.

    The application makes no network call at any point: this generator runs at development time
    and the icons ship inside the assembly as embedded resources.

    Run this after editing the icon table, then commit both the PNGs and the generated .axaml.
#>
[CmdletBinding()]
param(
    [string] $OutputDirectory = (Join-Path $PSScriptRoot '../src/GitVault.App/Assets'),
    [switch] $SkipDownload
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$baseUrl = 'https://raw.githubusercontent.com/nigeltao/tango-icon-library-pngs/main'
$iconDirectory = Join-Path $OutputDirectory 'ClassicIcons'

# Resource key -> Tango icon name. Names are the freedesktop icon-naming-spec names the Tango
# library ships under, prefixed with their category, exactly as the upstream mirror stores them.
$icons = [ordered]@{
    # Navigation tree
    'Computer'     = 'devices-computer'
    'Overview'     = 'categories-preferences-system'
    'Identities'   = 'apps-system-users'
    'Keys'         = 'emblems-emblem-readonly'
    'Agents'       = 'apps-utilities-system-monitor'
    'Credentials'  = 'actions-address-book-new'
    'Clients'      = 'categories-applications-development'
    'Repositories' = 'places-folder'
    'Profiles'     = 'actions-contact-new'
    'Snapshots'    = 'actions-document-save-as'
    'Logs'         = 'apps-accessories-text-editor'
    'Options'      = 'categories-preferences-desktop'

    # Toolbar and menus
    'Rescan'       = 'actions-view-refresh'
    'Preview'      = 'actions-document-print-preview'
    'Apply'        = 'actions-document-save'
    'Rollback'     = 'actions-edit-undo'
    'Copy'         = 'actions-edit-copy'
    'Properties'   = 'actions-document-properties'
    'Search'       = 'actions-system-search'
    'Add'          = 'actions-list-add'
    'Remove'       = 'actions-list-remove'
    'Delete'       = 'actions-edit-delete'
    'FolderOpen'   = 'actions-document-open'
    'Export'       = 'actions-document-save'
    'Exit'         = 'actions-system-log-out'
    'About'        = 'apps-help-browser'

    # Status and severity
    'SeverityHigh'   = 'status-dialog-error'
    'SeverityMedium' = 'status-dialog-warning'
    'SeverityLow'    = 'status-dialog-information'
    'SeverityOk'     = 'emblems-emblem-system'
    'Locked'         = 'actions-system-lock-screen'
    'Opaque'         = 'emblems-emblem-unreadable'
}

New-Item -ItemType Directory -Force -Path $iconDirectory | Out-Null

if (-not $SkipDownload) {
    Write-Host "Downloading $($icons.Count) icons from the Tango mirror..."

    Invoke-WebRequest -Uri "$baseUrl/COPYING" -OutFile (Join-Path $iconDirectory 'COPYING') -UseBasicParsing

    foreach ($entry in $icons.GetEnumerator()) {
        $destination = Join-Path $iconDirectory "$($entry.Value).png"
        if (Test-Path $destination) { continue }

        Invoke-WebRequest -Uri "$baseUrl/png-64/$($entry.Value).png" -OutFile $destination -UseBasicParsing
    }
}

# Remove PNGs no longer referenced, so a rename cannot leave an orphan shipping in the assembly.
$expected = @($icons.Values | ForEach-Object { "$_.png" }) + @('COPYING', 'README.md')
Get-ChildItem $iconDirectory -File |
    Where-Object { $expected -notcontains $_.Name } |
    ForEach-Object {
        Write-Host "  removing unreferenced $($_.Name)"
        Remove-Item $_.FullName -Force
    }

# --------------------------------------------------------------------------- resource dictionary
$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('<!--')
[void]$builder.AppendLine('  Generated by build/generate-classic-icons.ps1. Do not edit by hand.')
[void]$builder.AppendLine('')
[void]$builder.AppendLine('  Tango Icon Library 0.8.90, public domain. Each entry is a Bitmap rather than a geometry')
[void]$builder.AppendLine('  because Tango artwork is multi-path with gradients; see the generator for the reasoning.')
[void]$builder.AppendLine('-->')
[void]$builder.AppendLine('<ResourceDictionary xmlns="https://github.com/avaloniaui"')
[void]$builder.AppendLine('                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">')

foreach ($entry in $icons.GetEnumerator()) {
    $key = "Icon$($entry.Key)"
    $path = "avares://GitVault/Assets/ClassicIcons/$($entry.Value).png"
    [void]$builder.AppendLine("  <Bitmap x:Key=`"$key`">$path</Bitmap>")
}

[void]$builder.AppendLine('</ResourceDictionary>')

$outputPath = Join-Path $OutputDirectory 'ClassicIcons.axaml'
[System.IO.File]::WriteAllText($outputPath, $builder.ToString(), [System.Text.UTF8Encoding]::new($false))

# --------------------------------------------------------------------------- provenance note
$readme = @"
# Classic icon set

**Tango Icon Library 0.8.90 — public domain.**

The interface is styled after Win32-era administration utilities. Material Symbols, which the
first version of GitVault used, are thin monochrome outlines designed for modern mobile and web
surfaces; against classic chrome they read as a web application wearing a costume. Tango is the
icon language those utilities actually used.

## Licence

Public domain. ``COPYING`` in this directory is the upstream licence file, downloaded by the
generator alongside the artwork rather than transcribed, so the claim can be checked. Public
domain imposes no attribution obligation on this repository or on anyone who clones it, which
satisfies the project's licence rule (MIT / Apache-2.0 / BSD / MPL-2.0 / public domain only).

## Why rasters

Tango icons are multi-path artwork with gradients and highlights. They cannot be flattened into a
single ``StreamGeometry`` the way a Material Symbol can, and rendering SVG at runtime would mean
taking a new dependency. The generator downloads the 64px PNGs; the UI draws them at 16px in the
tree and menus and at 20px on the toolbar, with ``HighQuality`` interpolation. A 200% DPI display
therefore still has more source pixels than it needs.

## No network at runtime

The generator runs at development time. The PNGs are committed and shipped as embedded resources;
the application itself makes no network call, ever.

## Regenerating

``````
pwsh build/generate-classic-icons.ps1
``````

Edit the icon table at the top of the generator, run it, and commit both the PNGs and the
regenerated ``Assets/ClassicIcons.axaml``. Do not edit the generated dictionary by hand.
"@

[System.IO.File]::WriteAllText(
    (Join-Path $iconDirectory 'README.md'),
    $readme,
    [System.Text.UTF8Encoding]::new($false))

Write-Host "Wrote $outputPath"
Write-Host "  $($icons.Count) icons in $iconDirectory"
